probe peer-fingerprint "peer-fingerprint AB:CD:EF:01:23:45:67:89:AB:CD:EF:01:23:45:67:89:AB:CD:EF:01:23:45:67:89:AB:CD:EF:01:23:45:67:89"
probe keepalive "keepalive 10 60"
probe explicit-exit "explicit-exit-notify 2"
