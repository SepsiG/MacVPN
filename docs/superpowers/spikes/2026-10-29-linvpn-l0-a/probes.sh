#!/bin/bash
# Spike L0-1: writes one probe profile per directive under test into $2 (default ./probe). Each probe is the lab's
# openvpn-tun-dco.ovpn ($1, from scripts/vpn-lab/profiles.sh) with the directive inserted before <ca>, so an import
# diff against the base profile shows exactly what NetworkManager's OpenVPN plugin does with that one directive.
set -euo pipefail
B="${1:?usage: probes.sh BASE.ovpn [OUTDIR]}"
P="${2:-probe}"
mkdir -p "$P"
probe() { local n="$1"; shift; { sed -n '1,/^<ca>/p' "$B" | sed '$d'; printf '%s\n' "$@"; sed -n '/^<ca>/,$p' "$B"; } >"$P/probe_$n.ovpn"; }
probe route-nopull "route-nopull"
probe pull-filter "pull-filter ignore \"redirect-gateway\""
probe script-security "script-security 2"
probe up "up /bin/true"
probe down "down /bin/true"
probe static-challenge "static-challenge \"Enter code\" 1"
probe auth-retry "auth-retry interact"
probe data-ciphers "data-ciphers AES-256-GCM:CHACHA20-POLY1305" "data-ciphers-fallback AES-256-CBC"
probe dhcp-option "dhcp-option DNS 10.99.0.53" "dhcp-option DOMAIN lab.test"
probe block-outside-dns "block-outside-dns"
probe redirect-gateway-def1 "redirect-gateway def1"
probe redirect-gateway-ipv6 "redirect-gateway def1 ipv6 bypass-dhcp"
probe route-plain "route 10.99.20.0 255.255.255.0"
probe route-vpn-gateway "route 10.99.21.0 255.255.255.0 vpn_gateway"
probe route-net-gateway "route 192.0.2.0 255.255.255.0 net_gateway"
probe route-default "route 0.0.0.0 0.0.0.0"
probe route-ipv6 "route-ipv6 fd00:99::/64"
probe management "management 127.0.0.1 7505"
probe verb "verb 4"
probe compress-lz4v2 "compress lz4-v2"
probe compress-stub "compress stub-v2"
probe comp-lzo "comp-lzo yes"
