    }
    children {
      ikev2-eap {
        local_ts = $LAB_SERVICES_NET
        esp_proposals = $ESP2_PROPOSALS
      }
    }
  }
  ikev2-cert {
    version = 2
    proposals = $IKE2_PROPOSALS
    pools = ikev2
    send_cert = always
    unique = never
    local {
      auth = pubkey
      certs = server.pem
      id = $HOST
    }
    remote {
      auth = pubkey
      cacerts = ca.pem
    }
    children {
      ikev2-cert {
        local_ts = $LAB_SERVICES_NET
        esp_proposals = $ESP2_PROPOSALS
      }
    }
  }
  ikev2-psk {
    version = 2
    proposals = $IKE2_PROPOSALS
    pools = ikev2
    unique = never
    local {
      auth = psk
      id = $HOST
    }
    remote {
      auth = psk
    }
    children {
      ikev2-psk {
        local_ts = $LAB_SERVICES_NET
        esp_proposals = $ESP2_PROPOSALS
      }
    }
  }
  cisco-xauth {
    version = 1
    aggressive = yes
    proposals = $IKE1_PROPOSALS
    pools = cisco
    unique = never
    rekey_time = 0s
    local {
      auth = psk
      id = $HOST
    }
    remote {
      auth = psk
      id = keyid:$LAB_GROUP
    }
    remote-xauth {
      auth = xauth
    }
    children {
      cisco-xauth {
        local_ts = $LAB_SERVICES_NET
        esp_proposals = $ESP1_PROPOSALS
        rekey_time = 0s
      }
    }
  }
  l2tp-psk {
    version = 1
    proposals = $IKE1_PROPOSALS
    unique = never
    rekey_time = 0s
    local {
      auth = psk
    }
    remote {
      auth = psk
    }
    children {
      l2tp-psk {
        mode = transport
        local_ts = dynamic[udp/1701]
        remote_ts = dynamic[udp]
        esp_proposals = $ESP1_PROPOSALS
        rekey_time = 0s
      }
    }
  }
}
pools {
  ikev2 {
    addrs = 10.99.14.0/24
    dns = $LAB_DNS_IP
  }
  cisco {
    addrs = 10.99.15.0/24
    dns = $LAB_DNS_IP
    split_include = $LAB_SERVICES_NET
  }
}
secrets {
  ike-lab {
    secret = "$LAB_PSK"
  }
  eap-user {
    id = $LAB_USER
    secret = "$LAB_PASSWORD"
  }
  eap-otp {
    id = $LAB_OTP_USER
    secret = "$OTP_PASSWORD"
  }
  xauth-user {
    id = $LAB_USER
    secret = "$LAB_PASSWORD"
  }
  xauth-otp {
    id = $LAB_OTP_USER
    secret = "$OTP_PASSWORD"
  }
}
EOF

# pppd and accel-ppp share the format: client server secret addresses.
cat >"$SRV/chap-secrets" <<EOF
$LAB_USER * "$LAB_PASSWORD" *
$LAB_OTP_USER * "$OTP_PASSWORD" *
EOF

cat >"$SRV/openvpn-users.env" <<EOF
LAB_USER=$LAB_USER
LAB_PASSWORD=$LAB_PASSWORD
LAB_OTP_USER=$LAB_OTP_USER
LAB_OTP_CODE=$LAB_OTP_CODE
EOF

openvpn_server() { # name dev port network
  cat >"$SRV/openvpn-$1.conf" <<EOF
# Generated by profiles.sh: OpenVPN server "$1" (dev $2, UDP $3). Password login (no client certificate);
# the auth script also answers static (SCRV1) and dynamic (CRV1) challenges for $LAB_OTP_USER.
port $3
proto udp
dev $2
topology subnet
server $4 255.255.255.0
ca /state/pki/ca.pem
cert /state/pki/server.pem
key /state/pki/server.key
dh none
tls-crypt /state/pki/tls-crypt.key
data-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305:AES-256-CBC
verify-client-cert none
username-as-common-name
duplicate-cn
script-security 2
auth-user-pass-verify /lab/server/openvpn-auth.sh via-file
push "route ${LAB_SERVICES_NET%/*} 255.255.255.0"
push "dhcp-option DNS $LAB_DNS_IP"
push "dhcp-option DOMAIN lab.test"
keepalive 10 60
disable-dco
status /run/openvpn-$1.status 5
verb 3
EOF
}
openvpn_server tun tun0 1194 10.99.11.0
openvpn_server tap tap0 1195 10.99.12.0

cat >"$SRV/wg0.conf" <<EOF
