ovpn() { # file port dev extra-lines...
  local file="$1" port="$2" dev="$3"; shift 3
  {
    echo "client"
    echo "dev $dev"
    echo "proto udp"
    echo "remote $HOST $port"
    echo "nobind"
    echo "persist-key"
    echo "persist-tun"
    echo "remote-cert-tls server"
    echo "auth-user-pass"
    printf '%s\n' "$@"
    echo "<ca>"; echo "$CA_PEM"; echo "</ca>"
    echo "<tls-crypt>"; echo "$TLS_CRYPT"; echo "</tls-crypt>"
  } >"$file"
}

wg_client() { # file name address
  cat >"$1" <<EOF
[Interface]
PrivateKey = $(cat "$PKI/wg-$2.key")
Address = $3/32
DNS = $LAB_DNS_IP

[Peer]
PublicKey = $(cat "$PKI/wg-server.pub")
PresharedKey = $(cat "$PKI/wg-psk")
AllowedIPs = $LAB_SERVICES_NET, 10.99.13.1/32
Endpoint = $HOST:51820
PersistentKeepalive = 25
EOF
}

swan() { # file name port-line local-lines... (the remote side and the child are the same for every variant)
  local file="$1" name="$2" port_line="$3"; shift 3
  {
    echo "connections {"
    echo "  $name {"
    echo "    remote_addrs = $HOST"
    [ -z "$port_line" ] || echo "    $port_line"
    echo "    vips = 0.0.0.0"
    echo "    local {"
    printf '      %s\n' "$@"
    echo "    }"
    echo "    remote {"
    if [ "$1" = "auth = psk" ]; then echo "      auth = psk"; else echo "      auth = pubkey"; fi
    echo "      id = $HOST"
    echo "    }"
    echo "    children {"
    echo "      $name {"
    echo "        remote_ts = $LAB_SERVICES_NET"
    echo "      }"
    echo "    }"
    echo "  }"
    echo "}"
  } >"$file"
}

sstp() { # file port cert
  {
    echo "server=$HOST"
    echo "port=$2"
    echo "user=$LAB_USER"
    echo "cert=$3"
    echo "route_all=no"
    echo "peer_dns=yes"
    if [ "$3" = ca ]; then echo "<ca>"; echo "$CA_PEM"; echo "</ca>"; fi
  } >"$1"
}

native_sheet() { # file kind
  {
    echo "$2 – type these into New → $2 (MacVPN or WinVPN). Throwaway lab values."
    echo
    echo "Name:            Lab $2"
    echo "Server:          $HOST"
    echo "Account name:    $LAB_USER   (one-time code test: $LAB_OTP_USER, separator \",\", code $LAB_OTP_CODE)"
    echo "Password:        $LAB_PASSWORD"
    echo "Pre-shared key:  $LAB_PSK"
    [ "$2" != "Cisco IPsec" ] || echo "Group name:      $LAB_GROUP"
    echo "Send all traffic over VPN: off (the lab routes only $LAB_SERVICES_NET; on = no internet while connected)"
  } >"$1"
}

for os in macos windows; do
  d="$CLI/$os"
  ovpn "$d/openvpn-tun-dco.ovpn" 1194 tun "data-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305"
  ovpn "$d/openvpn-tun-cbc.ovpn" 1194 tun "data-ciphers AES-256-CBC"
