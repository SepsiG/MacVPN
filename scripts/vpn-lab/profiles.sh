#!/bin/bash
# Generates the VPN lab's state into $LAB_STATE (default scripts/vpn-lab/.state, git-ignored): throwaway
# credentials, a lab PKI, the server configs and the client profiles for MacVPN (client/macos) and WinVPN
# (client/windows), plus the profiles the selftest client container uses (client/selftest). Needs no Docker:
# OpenSSL 3+ only. Credentials and the PKI are made once and kept (so a re-run keeps installed CAs valid); --renew
# makes new ones, and a changed --host/--bind makes a new PKI (the names are in the certificates). The CA's private
# key is deleted once the certificates and the CRL exist: nothing is ever signed with it again (a new PKI is a whole
# new lab: --renew).
#
# Usage: profiles.sh [--host NAME] [--bind IPV4] [--sstp-port N] [--sstp-alt-port N] [--ike-alt-port N]
#                    [--crl-port N] [--renew]
set -euo pipefail
# shellcheck source=scripts/vpn-lab/lib.sh
. "$(dirname "$0")/lib.sh"

usage() { sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

RENEW=0
ARG_HOST="${LAB_HOST:-}"
ARG_BIND="${LAB_BIND:-}"
SSTP_PORT="${LAB_SSTP_PORT:-443}"
SSTP_ALT_PORT="${LAB_SSTP_ALT_PORT:-8443}"
IKE_ALT_PORT="${LAB_IKE_ALT_PORT:-4510}"
CRL_PORT="${LAB_CRL_PORT:-8081}"
while [ $# -gt 0 ]; do
  case "$1" in
    --host) ARG_HOST="${2:?--host needs a value}"; shift 2 ;;
    --bind) ARG_BIND="${2:?--bind needs a value}"; shift 2 ;;
    --sstp-port) SSTP_PORT="${2:?}"; shift 2 ;;
    --sstp-alt-port) SSTP_ALT_PORT="${2:?}"; shift 2 ;;
    --ike-alt-port) IKE_ALT_PORT="${2:?}"; shift 2 ;;
    --crl-port) CRL_PORT="${2:?}"; shift 2 ;;
    --renew) RENEW=1; shift ;;
    --dry-run) shift ;; # generation never touches Docker; accepted for symmetry with the other scripts
    -h|--help) usage 0 ;;
    *) echo "unknown argument: $1" >&2; usage 2 ;;
  esac
done
for p in "$SSTP_PORT" "$SSTP_ALT_PORT" "$IKE_ALT_PORT" "$CRL_PORT"; do
  [[ "$p" =~ ^[0-9]{1,5}$ ]] && [ "$p" -ge 1 ] && [ "$p" -le 65535 ] || die "invalid port: $p"
done

# Earlier settings (to keep the PKI when the names did not change).
OLD_HOST=""; OLD_BIND=""; OLD_CRL_PORT=""
if [ -f "$LAB_STATE/secrets.env" ]; then
  OLD_HOST="$(sed -n 's/^LAB_HOST=//p' "$LAB_STATE/secrets.env")"
  OLD_BIND="$(sed -n 's/^LAB_BIND=//p' "$LAB_STATE/secrets.env")"
  OLD_CRL_PORT="$(sed -n 's/^LAB_CRL_PORT=//p' "$LAB_STATE/secrets.env")"
fi
HOST="${ARG_HOST:-${ARG_BIND:-$OLD_HOST}}"
BIND="${ARG_BIND:-$OLD_BIND}"
[ -n "$HOST" ] || die "give the server name or address: --host NAME or --bind IPV4 (or LAB_HOST / LAB_BIND)"
is_ipv4 "$HOST" || is_hostname "$HOST" || die "invalid --host: $HOST"
[ -z "$BIND" ] || is_ipv4 "$BIND" || die "invalid --bind (an IPv4 address): $BIND"

OPENSSL_BIN="$(find_openssl)" || die "OpenSSL 3 or newer is needed (brew install openssl@3, or set OPENSSL)"
ossl() { "$OPENSSL_BIN" "$@"; }

umask 077
mkdir -p "$LAB_STATE"
STATE="$(cd "$LAB_STATE" && pwd)"
# The marker down.sh looks for before it deletes the folder (lib.sh, LAB_STATE_MARKER).
[ -f "$STATE/$LAB_STATE_MARKER" ] \
  || echo "MacVPN / WinVPN test lab state (written by scripts/vpn-lab/profiles.sh); down.sh deletes this folder" \
    >"$STATE/$LAB_STATE_MARKER"
PKI="$STATE/pki"; SRV="$STATE/server"; CLI="$STATE/client"

# Letters and digits only: every client (SSTP's pppd, swanctl's quoted strings, the RAS fields) takes them as typed.
rand_alnum() {
  local out=""
  while [ "${#out}" -lt "$1" ]; do
    out="$out$(ossl rand -base64 48 | tr -dc 'A-Za-z0-9')"
  done
  printf '%s' "${out:0:$1}"
}
rand_digits() { printf '%06d' $(( 16#$(ossl rand -hex 3) % 1000000 )); }

# --- credentials -------------------------------------------------------------------------------------------------
if [ "$RENEW" = 1 ] || [ ! -f "$STATE/secrets.env" ]; then
  LAB_USER="labuser"; LAB_OTP_USER="labotp"; LAB_GROUP="labgroup"
  LAB_PASSWORD="$(rand_alnum 20)"; LAB_PSK="$(rand_alnum 24)"; LAB_OTP_CODE="$(rand_digits)"
  LAB_P12_PASSWORD="$(rand_alnum 16)"
else
  LAB_USER="$(sed -n 's/^LAB_USER=//p' "$STATE/secrets.env")"
  LAB_OTP_USER="$(sed -n 's/^LAB_OTP_USER=//p' "$STATE/secrets.env")"
  LAB_GROUP="$(sed -n 's/^LAB_GROUP=//p' "$STATE/secrets.env")"
  LAB_PASSWORD="$(sed -n 's/^LAB_PASSWORD=//p' "$STATE/secrets.env")"
  LAB_PSK="$(sed -n 's/^LAB_PSK=//p' "$STATE/secrets.env")"
  LAB_OTP_CODE="$(sed -n 's/^LAB_OTP_CODE=//p' "$STATE/secrets.env")"
  LAB_P12_PASSWORD="$(sed -n 's/^LAB_P12_PASSWORD=//p' "$STATE/secrets.env")"
fi
cat >"$STATE/secrets.env" <<EOF
# Generated by scripts/vpn-lab/profiles.sh: throwaway lab credentials. Never commit; down.sh deletes them.
LAB_HOST=$HOST
LAB_BIND=$BIND
LAB_SSTP_PORT=$SSTP_PORT
LAB_SSTP_ALT_PORT=$SSTP_ALT_PORT
LAB_IKE_ALT_PORT=$IKE_ALT_PORT
LAB_CRL_PORT=$CRL_PORT
LAB_USER=$LAB_USER
LAB_PASSWORD=$LAB_PASSWORD
LAB_OTP_USER=$LAB_OTP_USER
LAB_OTP_CODE=$LAB_OTP_CODE
LAB_PSK=$LAB_PSK
LAB_GROUP=$LAB_GROUP
LAB_P12_PASSWORD=$LAB_P12_PASSWORD
EOF
OTP_PASSWORD="$LAB_PASSWORD,$LAB_OTP_CODE"

# --- PKI -----------------------------------------------------------------------------------------------------------
# A lab CA limited by name constraints to the lab's own names (the server's address/name and *.lab.test), so a
# client that trusts it for a test trusts nothing else signed by it. 90 days, RSA 3072 (every client takes it).
# Its extended key usages limit the whole chain (Windows: a CA's EKUs restrict every certificate below it) to what
# the lab uses: TLS server (SSTP, OpenVPN, IKEv2's server certificate), TLS client (the IKEv2 / OpenVPN client
# certificate) and the IKE intermediate (Windows' IKEv2); never code signing. The leaves keep their own EKUs
# (Windows' SSTP and IKEv2 check those on the server certificate). The key signs the two certificates and the CRL,
# then it is deleted: a CA key left on disk could issue anything the name constraints do not cover. The CRL is
# valid as long as the certificates (89 days); a new CRL means a new PKI (--renew, then trust the new CA).
# The certificates' common names are not host names (OpenSSL checks a host-like CN against the DNS constraints);
# the names are in the subjectAltName, which every client of the lab checks.
san_of() { if is_ipv4 "$1"; then echo "IP:$1"; else echo "DNS:$1"; fi; }
SERVER_SAN="$(san_of "$HOST")"
CONSTRAINTS="permitted;DNS:lab.test"
if is_ipv4 "$HOST"; then CONSTRAINTS="$CONSTRAINTS,permitted;IP:$HOST/255.255.255.255"; else CONSTRAINTS="$CONSTRAINTS,permitted;DNS:$HOST"; fi
if [ -n "$BIND" ] && [ "$BIND" != "$HOST" ]; then
  SERVER_SAN="$SERVER_SAN,IP:$BIND"
  CONSTRAINTS="$CONSTRAINTS,permitted;IP:$BIND/255.255.255.255"
fi
if [ "$RENEW" = 1 ] || [ ! -f "$PKI/ca.pem" ] || [ "$OLD_HOST" != "$HOST" ] || [ "$OLD_BIND" != "$BIND" ] \
   || [ "$OLD_CRL_PORT" != "$CRL_PORT" ]; then
  rm -rf "$PKI"; mkdir -p "$PKI"
  ossl req -x509 -new -newkey rsa:3072 -nodes -sha256 -days 90 -keyout "$PKI/ca.key" -out "$PKI/ca.pem" \
    -subj "/O=MacVPN test lab/CN=MacVPN Lab CA (throwaway)" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -addext "nameConstraints=critical,$CONSTRAINTS" \
    -addext "extendedKeyUsage=serverAuth,clientAuth,1.3.6.1.5.5.8.2.2" 2>/dev/null
  issue() { # name subject extensions...
    local name="$1" subj="$2"; shift 2
    printf '%s\n' "$@" >"$PKI/$name.ext"
    ossl req -new -newkey rsa:3072 -nodes -keyout "$PKI/$name.key" -out "$PKI/$name.csr" -subj "$subj" 2>/dev/null
    ossl x509 -req -sha256 -days 89 -in "$PKI/$name.csr" -CA "$PKI/ca.pem" -CAkey "$PKI/ca.key" \
      -CAcreateserial -extfile "$PKI/$name.ext" -out "$PKI/$name.pem" 2>/dev/null
    rm -f "$PKI/$name.csr" "$PKI/$name.ext"
  }
  # The IKE intermediate EKU (1.3.6.1.5.5.8.2.2) and a SAN equal to the dialled address: Windows' IKEv2 needs both.
  # The CRL distribution point: Windows' SSTP client checks revocation and refuses a server certificate whose
  # status it cannot learn (0x80092013); the lab serves its (empty) CRL on LAB_BIND:CRL_PORT.
  issue server "/O=MacVPN test lab/CN=MacVPN lab server" "basicConstraints=critical,CA:FALSE" \
    "keyUsage=critical,digitalSignature,keyEncipherment" "extendedKeyUsage=serverAuth,1.3.6.1.5.5.8.2.2" \
    "subjectAltName=$SERVER_SAN" "crlDistributionPoints=URI:http://$HOST:$CRL_PORT/ca.crl"
  issue client "/O=MacVPN test lab/CN=client.lab.test" "basicConstraints=critical,CA:FALSE" \
    "keyUsage=critical,digitalSignature,keyEncipherment" "extendedKeyUsage=clientAuth" \
    "subjectAltName=DNS:client.lab.test"
  # The CA's CRL (no revoked certificate), DER, valid as long as the certificates.
  mkdir -p "$PKI/ca-db"; : >"$PKI/ca-db/index.txt"; echo 1000 >"$PKI/ca-db/crlnumber"
  printf '[ca]\ndefault_ca = lab\n[lab]\ndatabase = %s\ncrlnumber = %s\ndefault_md = sha256\ndefault_crl_days = 89\n' \
    "$PKI/ca-db/index.txt" "$PKI/ca-db/crlnumber" >"$PKI/ca-db/ca.cnf"
  ossl ca -config "$PKI/ca-db/ca.cnf" -gencrl -keyfile "$PKI/ca.key" -cert "$PKI/ca.pem" -out "$PKI/ca.crl.pem" 2>/dev/null
  ossl crl -in "$PKI/ca.crl.pem" -outform DER -out "$PKI/ca.crl"
  # Nothing is signed with the CA again: its key, serial and CRL database go.
  rm -rf "${PKI:?}/ca.key" "$PKI/ca.srl" "$PKI/ca-db"
  ossl pkcs12 -export -in "$PKI/client.pem" -inkey "$PKI/client.key" -certfile "$PKI/ca.pem" \
    -name "MacVPN lab client" -passout "pass:$LAB_P12_PASSWORD" -out "$PKI/client.p12"
  ossl x509 -in "$PKI/ca.pem" -outform DER -out "$PKI/ca.cer"
  # WireGuard keys: raw X25519 keys are the last 32 bytes of the DER forms.
  for n in server macos windows selftest; do
    ossl genpkey -algorithm X25519 -out "$PKI/wg-$n.pem"
    ossl pkey -in "$PKI/wg-$n.pem" -outform DER | tail -c 32 | base64 >"$PKI/wg-$n.key"
    ossl pkey -in "$PKI/wg-$n.pem" -pubout -outform DER | tail -c 32 | base64 >"$PKI/wg-$n.pub"
  done
  ossl rand -base64 32 >"$PKI/wg-psk"
  # OpenVPN tls-crypt key (2048 bits in the "OpenVPN Static key V1" form, as `openvpn --genkey tls-crypt` writes).
  { echo "-----BEGIN OpenVPN Static key V1-----"; ossl rand -hex 256 | tr -d '\n' | fold -w 32; echo
    echo "-----END OpenVPN Static key V1-----"; } >"$PKI/tls-crypt.key"
fi
# Only the CRL is served (the crl container mounts this folder, never the rest of the state).
rm -rf "$STATE/crl"; mkdir -p "$STATE/crl"; cp "$PKI/ca.crl" "$STATE/crl/ca.crl"; chmod 755 "$STATE/crl"; chmod 644 "$STATE/crl/ca.crl"
CA_PEM="$(cat "$PKI/ca.pem")"
TLS_CRYPT="$(cat "$PKI/tls-crypt.key")"

# --- server configs ----------------------------------------------------------------------------------------------
rm -rf "$SRV"; mkdir -p "$SRV"
IKE2_PROPOSALS="aes256-sha256-modp2048,aes256gcm16-prfsha256-modp2048,aes256-sha256-ecp256,aes256gcm16-prfsha384-ecp384,aes256-sha384-ecp384,aes256-sha1-modp2048,aes256-sha1-modp1024,aes128-sha1-modp1024,aes256-sha256-modp1024"
ESP2_PROPOSALS="aes256gcm16,aes256-sha256,aes256-sha384,aes256-sha1,aes128-sha1"
IKE1_PROPOSALS="aes256-sha256-modp2048,aes256-sha1-modp2048,aes256-sha256-modp1024,aes256-sha1-modp1024,aes128-sha1-modp1024,3des-sha1-modp1024"
ESP1_PROPOSALS="aes256-sha256,aes256-sha1,aes128-sha1,3des-sha1"

cat >"$SRV/swanctl.conf" <<EOF
# Generated by profiles.sh. IKEv2 (EAP-MSCHAPv2, PSK, certificate), IKEv1 XAUTH + PSK (Cisco IPsec) and
# L2TP/IPsec (IKEv1 PSK, transport mode) on one charon. Clients reach only $LAB_SERVICES_NET.
connections {
  ikev2-eap {
    version = 2
    proposals = $IKE2_PROPOSALS
    pools = ikev2
    send_cert = always
    unique = never
    local {
      auth = pubkey
      certs = server.pem
      id = $HOST
    }
    remote {
